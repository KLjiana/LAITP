@dataclass(frozen=True)
class Issue:
    """单条校验问题。

    ``location`` 使用 ``files[2].sha256`` 形式定位字段或文件，便于界面和测试定位。
    """

    code: Code
    stage: Stage
    location: str
    message: str

    def to_dict(self) -> dict[str, str]:
        return {
            "code": self.code.value,
            "stage": self.stage.value,
            "location": self.location,
            "message": self.message,
        }


class Report:
    """校验结果。一次校验可以包含多条问题，按发现顺序保留。"""

    def __init__(self, issues: Iterable[Issue] = ()) -> None:
        self._issues: list[Issue] = list(issues)

    @property
    def ok(self) -> bool:
        return not self._issues

    @property
    def issues(self) -> tuple[Issue, ...]:
        return tuple(self._issues)

    def add(self, code: Code, stage: Stage, location: str, message: str) -> None:
        self._issues.append(Issue(code=code, stage=stage, location=location, message=message))

    def extend(self, issues: Iterable[Issue]) -> None:
        self._issues.extend(issues)

    def codes(self) -> tuple[str, ...]:
        return tuple(issue.code.value for issue in self._issues)

    def has(self, code: Code) -> bool:
        return any(issue.code is code for issue in self._issues)

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "issues": [issue.to_dict() for issue in self._issues],
        }

    def __repr__(self) -> str:  # pragma: no cover - 调试辅助
        return f"Report(ok={self.ok}, codes={self.codes()})"
